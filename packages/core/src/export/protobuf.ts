// Protocol Buffers の出力（FR-OUT-01、P-63）。テーブルごとにスキーマ（proto3 の .proto）とバイナリ（.pb）を出す。
// .pb は <Table>Table メッセージ（repeated <Table> records = 1）を 1 つ符号化したもの。フィールド番号はテーブルの
// `proto` で列ごとに固定し、削除した列の番号と名前は reserved にする（model/proto.ts）。
// 符号化は自前で行い、フィールドは番号の順に、数値のリストは packed で書く（同じ入力から同じバイト列。FR-OUT-03）
import type { RawValue } from '../model/cell';
import type { FieldDef, FieldType } from '../model/field';
import { isListType } from '../model/field';
import type { TableProto } from '../model/proto';
import { isProtoIdentifier, scalarProtoType } from '../model/proto';

export { isProtoIdentifier };

/** 出力する proto のパッケージ名 */
export const PROTO_PACKAGE = 'sheetcraft';

/** テーブル名・列名（英小文字・数字・_）から型名を作る: skill_effect → SkillEffect */
export function protoMessageName(table: string): string {
  return table
    .split('_')
    .filter((part) => part !== '')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

/** テーブルの .proto で定義するメッセージの名前（レコードと、レコードの並び） */
export function protoMessageNames(table: string): [record: string, list: string] {
  const record = protoMessageName(table);
  return [record, `${record}Table`];
}

/** protoc が作る JSON 名（_ を除いて次の文字を大文字にする）。proto3 ではこれが重なるとエラーになる */
export function protoJsonName(field: string): string {
  let out = '';
  let upper = false;
  for (const ch of field) {
    if (ch === '_') upper = true;
    else {
      out += upper ? ch.toUpperCase() : ch;
      upper = false;
    }
  }
  return out;
}

/** JSON 名が重なる列の組（protoc がエラーにする。P-63） */
export function protoFieldConflicts(columns: readonly FieldDef[]): [string, string][] {
  const seen = new Map<string, string>();
  const conflicts: [string, string][] = [];
  for (const column of columns) {
    const json = protoJsonName(column.name);
    const other = seen.get(json);
    if (other === undefined) seen.set(json, column.name);
    else conflicts.push([other, column.name]);
  }
  return conflicts;
}

/** コメントに入れる表示名（改行と NUL は空白にする。protoc は NUL を含むファイルを読めない） */
function comment(text: string | undefined): string {
  return text === undefined || text === '' ? '' : ` // ${text.replace(/\s*[\r\n]+\s*/g, ' ').replaceAll('\0', ' ')}`;
}

/** 列名 → フィールド番号。proto は今の列に合わせたもの（resolveProto）で、どの列も番号を持つ */
function fieldNumbers(columns: readonly FieldDef[], proto: TableProto): number[] {
  const numbers = new Map(proto.fields);
  return columns.map((column) => {
    const n = numbers.get(column.name);
    if (n === undefined) throw new Error(`no field number for ${column.name}`);
    return n;
  });
}

/**
 * .proto のテキスト。フィールドは列の順で、番号は proto のもの（出力しない列の番号は書かない）。
 * reserved の番号と名前は先頭に書く。未入力を区別できるよう、スカラーは optional にする
 */
export function emitProtoSchema(table: string, displayName: string | undefined, columns: readonly FieldDef[], proto: TableProto): string {
  const [record, list] = protoMessageNames(table);
  const numbers = fieldNumbers(columns, proto);
  const lines = [
    `// Generated by SheetCraft from the table "${table}". Do not edit.`,
    'syntax = "proto3";',
    '',
    `package ${PROTO_PACKAGE};`,
    '',
    `message ${record} {${comment(displayName)}`,
  ];
  if (proto.reserved.length > 0) lines.push(`  reserved ${proto.reserved.map((r) => r.number).join(', ')};`);
  const names = proto.reserved.flatMap((r) => (r.name === undefined ? [] : [`"${r.name}"`]));
  if (names.length > 0) lines.push(`  reserved ${names.join(', ')};`);
  columns.forEach((column, i) => {
    const label = isListType(column.type) ? 'repeated' : 'optional';
    lines.push(`  ${label} ${scalarProtoType(column.type)} ${column.name} = ${numbers[i]};${comment(column.display_name)}`);
  });
  lines.push('}', '', `message ${list} {`, `  repeated ${record} records = 1;`, '}');
  return `${lines.join('\n')}\n`;
}

// ---- 符号化 ----

const WIRE_VARINT = 0;
const WIRE_I64 = 1;
const WIRE_LEN = 2;

/** UTF-8 のバイト列（孤立したサロゲートは U+FFFD にする。TextEncoder と同じ） */
function utf8(s: string): Uint8Array {
  const out: number[] = [];
  for (const ch of s) {
    let cp = ch.codePointAt(0) as number;
    if (cp >= 0xd800 && cp <= 0xdfff) cp = 0xfffd;
    if (cp < 0x80) out.push(cp);
    else if (cp < 0x800) out.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f));
    else if (cp < 0x10000) out.push(0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));
    else out.push(0xf0 | (cp >> 18), 0x80 | ((cp >> 12) & 0x3f), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));
  }
  return Uint8Array.from(out);
}

class ByteWriter {
  private buf = new Uint8Array(256);
  private len = 0;
  private readonly scratch = new DataView(new ArrayBuffer(8));

  private reserve(n: number): void {
    if (this.len + n <= this.buf.length) return;
    let size = this.buf.length * 2;
    while (size < this.len + n) size *= 2;
    const next = new Uint8Array(size);
    next.set(this.buf.subarray(0, this.len));
    this.buf = next;
  }

  byte(b: number): void {
    this.reserve(1);
    this.buf[this.len++] = b;
  }

  bytes(data: Uint8Array): void {
    this.reserve(data.length);
    this.buf.set(data, this.len);
    this.len += data.length;
  }

  /** 符号なしの varint。負の数は 64 ビットの 2 の補数（10 バイト）にする */
  varint(value: number | bigint): void {
    if (typeof value === 'number' && value >= 0 && Number.isSafeInteger(value)) {
      let v = value;
      while (v >= 0x80) {
        this.byte((v % 0x80) | 0x80);
        v = Math.floor(v / 0x80);
      }
      this.byte(v);
      return;
    }
    let v = BigInt.asUintN(64, BigInt(value));
    while (v >= 0x80n) {
      this.byte(Number(v & 0x7fn) | 0x80);
      v >>= 7n;
    }
    this.byte(Number(v));
  }

  tag(field: number, wire: number): void {
    this.varint(field * 8 + wire);
  }

  double(value: number): void {
    this.scratch.setFloat64(0, value, true);
    this.bytes(new Uint8Array(this.scratch.buffer));
  }

  /** 長さ付きのフィールド */
  lengthDelimited(field: number, data: Uint8Array): void {
    this.tag(field, WIRE_LEN);
    this.varint(data.length);
    this.bytes(data);
  }

  finish(): Uint8Array {
    return this.buf.slice(0, this.len);
  }
}

function writeScalar(w: ByteWriter, field: number, type: FieldType, raw: RawValue): void {
  switch (scalarProtoType(type)) {
    case 'int64':
      w.tag(field, WIRE_VARINT);
      w.varint(raw as number | bigint);
      return;
    case 'double':
      w.tag(field, WIRE_I64);
      w.double(Number(raw));
      return;
    case 'bool':
      w.tag(field, WIRE_VARINT);
      w.byte(raw === true ? 1 : 0);
      return;
    case 'string':
      w.lengthDelimited(field, utf8(String(raw)));
      return;
  }
}

function writeList(w: ByteWriter, field: number, type: FieldType, items: readonly RawValue[]): void {
  if (items.length === 0) return;
  const proto = scalarProtoType(type);
  if (proto === 'string') {
    for (const item of items) w.lengthDelimited(field, utf8(String(item)));
    return;
  }
  // proto3 の数値の repeated は packed
  const packed = new ByteWriter();
  for (const item of items) {
    if (proto === 'double') packed.double(Number(item));
    else packed.varint(item as number | bigint);
  }
  w.lengthDelimited(field, packed.finish());
}

/** <Table>Table メッセージのバイト列。フィールドは番号の順に書き、未入力（undefined）のフィールドは書かない */
export function encodeProtoTable(columns: readonly FieldDef[], rows: readonly (RawValue | undefined)[][], proto: TableProto): Uint8Array {
  const numbers = fieldNumbers(columns, proto);
  const order = columns.map((_, i) => i).sort((a, b) => numbers[a] - numbers[b]);
  const out = new ByteWriter();
  for (const row of rows) {
    const rec = new ByteWriter();
    for (const i of order) {
      const raw = row[i];
      if (raw === undefined) continue;
      const column = columns[i];
      if (Array.isArray(raw)) writeList(rec, numbers[i], column.type, raw);
      else writeScalar(rec, numbers[i], column.type, raw);
    }
    out.lengthDelimited(1, rec.finish());
  }
  return out.finish();
}
