import { describe, expect, it } from 'vitest';
import { Calculator } from '../calc';
import { loadSample, testProject } from '../calc/test-project';
import { ExportCode } from './codes';
import { planExport } from './index';
import { protoJsonName, protoMessageName } from './protobuf';

const BASE_ID = 'base_fields:\n  - { name: id, type: int, primary: true }\n';

function hex(bytes: string | Uint8Array): string {
  if (typeof bytes === 'string') throw new Error('バイナリではない');
  return [...bytes].map((b) => b.toString(16).padStart(2, '0')).join(' ');
}

describe('CSV の出力（P-62）', () => {
  it('1 行目は列名。未入力は空欄、リストは JSON の配列、区切り・引用符・改行を含む値は引用符で囲む', async () => {
    const project = await loadSample('basic-yaml');
    const result = planExport(project, new Calculator(project), { format: 'csv' });
    expect(result.ok).toBe(true);
    expect(result.files.map((f) => f.path)).toEqual(['build/character.csv', 'build/skill.csv', 'build/stage.csv']);
    expect(result.files[0].content).toBe(
      'id,version,name,rarity,hp,defense,effective_hp,skill_ids,element,start_at,power,code\n' +
        '1,,勇者アルス,SSR,1200,30,1560,"[1,3]","[""火"",""光""]",2026-10-13T12:00:00+09:00,9007199254740993,NO\n' +
        '2,,魔法使いリナ,SR,800,10,1600,"[1,2]","[""水""]",2026-10-20T00:00:00+09:00,12000,1.10\n' +
        '3,0.1.2,盗賊カイ,R,650,0,650,,"[""風"",""闇""]",,800,null\n',
    );
  });

  it('default の空文字列と空のリストは未入力（空欄）と区別する。セル内の改行と引用符', async () => {
    const project = await testProject({
      baseFields: BASE_ID,
      tables: {
        t: `fields:
  - { name: s, type: string, default: "" }
  - { name: l, type: list<string>, default: [] }
  - { name: n, type: string }
  - { name: b, type: bool }
records:
  - { id: 1, s: "a,\\"b\\"\\nc", l: ["x,y"], b: true }
  - { id: 2 }
`,
      },
    });
    const result = planExport(project, new Calculator(project), { format: 'csv' });
    expect(result.files[0].content).toBe('id,s,l,n,b\n1,"a,""b""\nc","[""x,y""]",,true\n2,"",[],,\n');
  });

  it('レコードが無ければ列名の行だけ', async () => {
    const project = await testProject({ baseFields: BASE_ID, tables: { t: 'fields: []\nrecords: []\n' } });
    expect(planExport(project, new Calculator(project), { format: 'csv' }).files[0].content).toBe('id\n');
  });
});

describe('Protocol Buffers の出力（P-63）', () => {
  it('テーブルごとに .proto と .pb。スカラーは optional、リストは repeated、番号は列の順', async () => {
    const project = await loadSample('basic-yaml');
    const calc = new Calculator(project);
    const result = planExport(project, calc, { format: 'protobuf', tables: ['stage'] });
    expect(result.ok).toBe(true);
    expect(result.files.map((f) => f.path)).toEqual(['build/stage.proto', 'build/stage.pb']);
    expect(result.files[0].content).toBe(
      [
        '// Generated by MasterData Maker from the table "stage". Do not edit.',
        'syntax = "proto3";',
        '',
        'package masterdata_maker;',
        '',
        'message Stage { // ステージ',
        '  optional int64 id = 1; // ID',
        '  optional string version = 2; // バージョン',
        '  optional string name = 3; // 名前',
        '  optional int64 boss_id = 4; // ボス',
        '}',
        '',
        'message StageTable {',
        '  repeated Stage records = 1;',
        '}',
        '',
      ].join('\n'),
    );
    // 同じ入力からは同じバイト列（FR-OUT-03）
    expect(planExport(project, new Calculator(project), { format: 'protobuf', tables: ['stage'] })).toEqual(result);
  });

  it('ワイヤ形式: int は varint（負の数は 10 バイト）、float は double、文字列は UTF-8、数値のリストは packed、未入力は書かない', async () => {
    const project = await testProject({
      baseFields: BASE_ID,
      tables: {
        t: `fields:
  - { name: a, type: int }
  - { name: s, type: string }
  - { name: l, type: list<int> }
  - { name: f, type: float }
  - { name: b, type: bool }
  - { name: sl, type: list<string> }
records:
  - { id: 1, a: -1, s: あ, l: [1, 300], f: 0.5, b: false, sl: [x, ""] }
  - { id: 2 }
`,
      },
    });
    const result = planExport(project, new Calculator(project), { format: 'protobuf' });
    const record1 = [
      '08 01', // id = 1
      '10 ff ff ff ff ff ff ff ff ff 01', // a = -1
      '1a 03 e3 81 82', // s = "あ"
      '22 03 01 ac 02', // l = [1, 300]（packed）
      '29 00 00 00 00 00 00 e0 3f', // f = 0.5
      '30 00', // b = false（optional なので既定値でも書く）
      '3a 01 78', // sl[0] = "x"
      '3a 00', // sl[1] = ""
    ].join(' ');
    expect(hex(result.files[1].content)).toBe(`0a 27 ${record1} 0a 02 08 02`);
  });

  it('int64 は精度を落とさない', async () => {
    const project = await testProject({
      baseFields: BASE_ID,
      tables: { t: 'fields:\n  - { name: v, type: int64 }\nrecords:\n  - { id: 1, v: 9223372036854775807 }\n' },
    });
    const result = planExport(project, new Calculator(project), { format: 'protobuf' });
    expect(hex(result.files[1].content)).toBe('0a 0c 08 01 10 ff ff ff ff ff ff ff ff 7f');
  });

  it('名前の変換', () => {
    expect(protoMessageName('skill_effect')).toBe('SkillEffect');
    expect(protoMessageName('stage_1')).toBe('Stage1');
    expect(protoJsonName('boss_id')).toBe('bossId');
    expect(protoJsonName('hp_')).toBe('hp');
  });

  it('メッセージ名・JSON 名が重なれば、force でも出力しない', async () => {
    const project = await testProject({
      baseFields: BASE_ID,
      tables: {
        foo: 'fields:\n  - { name: a_1, type: int }\n  - { name: a1, type: int }\nrecords: []\n',
        foo_table: 'fields: []\nrecords: []\n',
        bar: 'fields: []\nrecords: []\n',
      },
    });
    const calc = new Calculator(project);
    const result = planExport(project, calc, { format: 'protobuf', force: true });
    expect(result.ok).toBe(false);
    expect(result.blocked).toBe(true);
    expect(result.files).toEqual([]);
    expect(result.diagnostics.map((d) => [d.code, d.table, d.params])).toEqual([
      [ExportCode.protoMessageConflict, 'foo', { message: 'FooTable', other: 'foo_table' }],
      [ExportCode.protoFieldConflict, 'foo', { field: 'a1', other: 'a_1' }],
      [ExportCode.protoMessageConflict, 'foo_table', { message: 'FooTable', other: 'foo' }],
    ]);
    // 重ならないテーブルだけなら出力する。ほかの形式では重なりを問わない
    expect(planExport(project, calc, { format: 'protobuf', tables: ['bar'] }).ok).toBe(true);
    expect(planExport(project, calc, { format: 'csv' }).ok).toBe(true);
  });

  it('proto の識別子にならない名前（_1 のメッセージ名 1、書式に合わない列名）は force でも出力しない', async () => {
    const project = await testProject({
      baseFields: BASE_ID,
      tables: {
        _1: 'fields: []\nrecords: []\n',
        t: 'fields:\n  - { name: bad-name, type: int }\nrecords: []\n',
      },
    });
    const calc = new Calculator(project);
    const result = planExport(project, calc, { format: 'protobuf', force: true });
    expect(result.ok).toBe(false);
    expect(result.blocked).toBe(true);
    expect(result.diagnostics.filter((d) => d.code === ExportCode.protoInvalidName).map((d) => [d.table, d.params])).toEqual([
      ['_1', { name: '_1', proto: '1' }],
      ['t', { name: 'bad-name', proto: 'bad-name' }],
    ]);
    // 列名の書式エラーは、ほかの形式なら force で出力できる
    const json = planExport(project, calc, { force: true });
    expect([json.ok, json.blocked]).toEqual([true, false]);
  });

  it('表示名の改行と NUL はコメントに入れない（protoc は NUL を読めない）', async () => {
    const project = await testProject({
      baseFields: BASE_ID,
      tables: { t: 'display_name: "a\\0b\\nc"\nfields:\n  - { name: v, type: int, display_name: "x\\r\\n  y" }\nrecords: []\n' },
    });
    const proto = planExport(project, new Calculator(project), { format: 'protobuf' }).files[0].content as string;
    expect(proto).toContain('message T { // a b c\n');
    expect(proto).toContain('  optional int64 v = 2; // x y\n');
  });
});
